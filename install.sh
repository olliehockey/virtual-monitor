#!/usr/bin/env bash
# Install vm (virtual-monitor) for the current user.
#
# What it does:  copies vm to ~/.local/share/virtual-monitor, adds ~/.local/bin/vm,
#                installs shell completion, and (only if you already have devices)
#                refreshes vm's own unit files.
# What it never does:  use sudo; start, stop, enable or restart any service;
#                enable anything at login; touch your normal (Mac) Sunshine, its
#                drop-ins, config, credentials or runtime state; modify a legacy setup.
#
# Usage: ./install.sh [--yes] [--dry-run]
set -euo pipefail

YES=0
DRY=0
for arg in "$@"; do
  case $arg in
    -y|--yes) YES=1 ;;
    -n|--dry-run) DRY=1 ;;
    -h|--help) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "Unknown option: $arg (try --help)" >&2; exit 2 ;;
  esac
done

SRC="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
DEST="${XDG_DATA_HOME:-$HOME/.local/share}/virtual-monitor"
BIN_DIR="$HOME/.local/bin"
LAUNCHER="$BIN_DIR/vm"
MARK="# vm launcher (virtual-monitor)"
BASH_COMP="${XDG_DATA_HOME:-$HOME/.local/share}/bash-completion/completions/vm"
ZSH_COMP="${XDG_DATA_HOME:-$HOME/.local/share}/zsh/site-functions/_vm"
FISH_COMP="${XDG_CONFIG_HOME:-$HOME/.config}/fish/completions/vm.fish"

if [[ -t 1 && -z ${NO_COLOR:-} ]]; then
  bold() { printf '\033[1m%s\033[0m\n' "$*"; }
else
  bold() { printf '%s\n' "$*"; }
fi
step() { printf '  › %s\n' "$*"; }
die()  { printf '✕ %s\n' "$*" >&2; exit 1; }
run()  { if (( DRY )); then printf '    [dry-run] %s\n' "$*"; else "$@"; fi; }

# --- 1. Requirements ----------------------------------------------------------
PY="$(command -v python3 || true)"
[[ -x /usr/bin/python3 ]] && PY=/usr/bin/python3
[[ -n $PY ]] || die "python3 not found"
"$PY" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 11) else 1)' \
  || die "Python 3.11+ is required (found $("$PY" --version 2>&1))"
[[ -f $SRC/virtual_monitor/cli.py ]] || die "Run this from the unpacked virtual-monitor folder"

bold "Installing vm (virtual-monitor) $(PYTHONPATH="$SRC" "$PY" -c 'import virtual_monitor as v; print(v.__version__)')"

# --- 2. Look for legacy setups BEFORE changing anything (read-only) ------------
echo
PYTHONPATH="$SRC" "$PY" -m virtual_monitor _legacy-report
LEGACY_COUNT="$(PYTHONPATH="$SRC" "$PY" -m virtual_monitor _legacy-report --json | "$PY" -c 'import json,sys; print(len(json.load(sys.stdin)))')"
if (( LEGACY_COUNT > 0 )); then
  echo "  The installer leaves all of the above exactly as it is."
  echo "  Afterwards, 'vm doctor' shows the exact files and a manual migration procedure."
  if (( ! YES )); then
    if [[ -t 0 ]]; then
      read -r -p "  Continue installing vm? [y/N] " answer
      [[ $answer == [yY]* ]] || { echo "Cancelled; nothing was changed."; exit 1; }
    else
      die "Legacy setup found and no terminal to confirm. Re-run with --yes to continue."
    fi
  fi
fi

# --- 3. Don't clobber someone else's `vm` ---------------------------------------
if [[ -e $LAUNCHER ]] && ! grep -qF "$MARK" "$LAUNCHER" 2>/dev/null; then
  die "$LAUNCHER exists and isn't vm's launcher. Move it away and re-run."
fi
other="$(type -P vm 2>/dev/null || true)"
if [[ -n $other && $other != "$LAUNCHER" ]]; then
  echo "  ! Another 'vm' is on your PATH ($other); ~/.local/bin/vm must come before it."
fi

# --- 4. Copy the program (staged, then swapped in) ------------------------------
echo
bold "Installing files"
step "program → $DEST"
run mkdir -p "$(dirname "$DEST")"
STAGE="$DEST.new.$$"
run rm -rf "$STAGE"
run mkdir -p "$STAGE"
run cp -R "$SRC/virtual_monitor" "$STAGE/"
run find "$STAGE" -name '__pycache__' -prune -exec rm -rf {} +
[[ -d $SRC/docs ]] && run cp -R "$SRC/docs" "$STAGE/"
run cp "$SRC/README.md" "$SRC/LICENSE" "$SRC/uninstall.sh" "$STAGE/"
if [[ -d $DEST ]]; then
  run mv "$DEST" "$DEST.old.$$"
  run mv "$STAGE" "$DEST"
  run rm -rf "$DEST.old.$$"
else
  run mv "$STAGE" "$DEST"
fi

step "command → $LAUNCHER"
run mkdir -p "$BIN_DIR"
if (( ! DRY )); then
  cat > "$LAUNCHER.tmp" <<EOF
#!/bin/sh
$MARK - generated by install.sh, safe to delete with uninstall.sh
PYTHONPATH="$DEST\${PYTHONPATH:+:\$PYTHONPATH}" exec "$PY" -m virtual_monitor "\$@"
EOF
  chmod 755 "$LAUNCHER.tmp"
  mv "$LAUNCHER.tmp" "$LAUNCHER"
fi

step "shell completion (bash, zsh$(command -v fish >/dev/null && echo ', fish'))"
run mkdir -p "$(dirname "$BASH_COMP")" "$(dirname "$ZSH_COMP")"
if (( ! DRY )); then
  PYTHONPATH="$DEST" "$PY" -m virtual_monitor completion bash > "$BASH_COMP"
  PYTHONPATH="$DEST" "$PY" -m virtual_monitor completion zsh > "$ZSH_COMP"
  if command -v fish >/dev/null; then
    mkdir -p "$(dirname "$FISH_COMP")"
    PYTHONPATH="$DEST" "$PY" -m virtual_monitor completion fish > "$FISH_COMP"
  fi
fi

# --- 5. Refresh vm's own unit files only if devices already exist ---------------
CONFIG="${XDG_CONFIG_HOME:-$HOME/.config}/virtual-monitor/devices.toml"
if [[ -f $CONFIG ]]; then
  step "refreshing vm's own unit files (nothing is started or enabled)"
  run "$LAUNCHER" sync
fi

# --- Done -----------------------------------------------------------------------
echo
bold "Done. Nothing was started, and nothing will start at login."
case ":$PATH:" in
  *":$BIN_DIR:"*) ;;
  *) echo "  ! $BIN_DIR isn't on your PATH. Add it, e.g.: echo 'export PATH=\"\$HOME/.local/bin:\$PATH\"' >> ~/.bashrc" ;;
esac
cat <<'EOF'

Next (in a new terminal):
  vm doctor
  vm add ipad ipad-pro-11      # presets: iphone-13 ipad-pro-11 macbook-air macbook-air-15, or WIDTHxHEIGHT
  vm enable ipad               # turns it on and pairs it the first time
EOF
